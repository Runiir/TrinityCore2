CREATE TABLE IF NOT EXISTS `experiment_bot_runs` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `experiment_name` varchar(128) NOT NULL,
  `config_json` text NULL,
  `brain_version` varchar(64) NOT NULL DEFAULT '',
  `status` varchar(32) NOT NULL DEFAULT 'created',
  `started_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `ended_at` timestamp NULL DEFAULT NULL,
  `summary_json` text NULL,
  PRIMARY KEY (`id`),
  KEY `idx_experiment_bot_runs_status` (`status`),
  KEY `idx_experiment_bot_runs_name` (`experiment_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Autonomous bot experiment runs';

