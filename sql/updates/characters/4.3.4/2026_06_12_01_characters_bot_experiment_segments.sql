CREATE TABLE IF NOT EXISTS `experiment_bot_segments` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `parent_run_id` bigint unsigned NULL,
  `experiment_name` varchar(128) NOT NULL,
  `trigger_event_id` bigint unsigned NULL,
  `clip_id` bigint unsigned NULL,
  `bot_guid` int unsigned NOT NULL,
  `brain_version` varchar(64) NULL,
  `status` varchar(32) NOT NULL DEFAULT 'running',
  `result` varchar(64) NULL,
  `started_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `ended_at` timestamp NULL DEFAULT NULL,
  `map_id` int unsigned NULL,
  `zone_id` int unsigned NULL,
  `area_id` int unsigned NULL,
  `x` float NULL,
  `y` float NULL,
  `z` float NULL,
  `trigger_json` text NULL,
  `summary_json` text NULL,
  PRIMARY KEY (`id`),
  KEY `idx_experiment_bot_segments_parent_run` (`parent_run_id`),
  KEY `idx_experiment_bot_segments_name` (`experiment_name`),
  KEY `idx_experiment_bot_segments_bot_status` (`bot_guid`, `status`),
  KEY `idx_experiment_bot_segments_clip` (`clip_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Short telemetry-triggered autonomous bot experiment segments';
